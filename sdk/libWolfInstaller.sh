#!/bin/bash
# libWolf SDK self-extracting installer for Linux / macOS
# Kullanim: bash libWolfInstaller.sh  (veya chmod +x && ./libWolfInstaller.sh)
set -e

INSTALL_DIR="${LIBWOLF_DIR:-$HOME/.local/share/Arctian/libWolf}"
echo "libWolf SDK kuruluyor: $INSTALL_DIR"

mkdir -p "$INSTALL_DIR"
# --- BEGIN PAYLOAD ---
# (payload is appended below by the build script)
# --- END PAYLOAD ---

# Extract payload (base64-encoded tarball after __PAYLOAD__ marker)
PAYLOAD_LINE=$(grep -n "^__PAYLOAD__$" "$0" | tail -1 | cut -d: -f1)
tail -n +$((PAYLOAD_LINE + 1)) "$0" | base64 -d | tar -xz -C "$INSTALL_DIR"

# Add to PATH (bash/zsh)
SHELL_RC=""
if [ -n "$ZSH_VERSION" ] || [ "$(basename "$SHELL")" = "zsh" ]; then
    SHELL_RC="$HOME/.zshrc"
elif [ -f "$HOME/.bashrc" ]; then
    SHELL_RC="$HOME/.bashrc"
else
    SHELL_RC="$HOME/.profile"
fi

if ! grep -q "Arctian/libWolf" "$SHELL_RC" 2>/dev/null; then
    echo "" >> "$SHELL_RC"
    echo "# libWolf SDK" >> "$SHELL_RC"
    echo "export PATH=\"$INSTALL_DIR:\$PATH\"" >> "$SHELL_RC"
    echo "PATH guncellendi: $SHELL_RC"
fi

echo ""
echo "Kurulum tamamlandi!"
echo "Konum: $INSTALL_DIR"
echo ""
echo "Yeni bir terminal acip deneyin:"
echo "  cd $INSTALL_DIR/examples/merhaba"
echo "  bash build.sh"
echo ""
echo "Arctian'a kurmak icin uretilen .wlf dosyasini kopyalayin."
exit 0
