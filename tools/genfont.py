lines = [
    '#ifndef FONT8X8_H',
    '#define FONT8X8_H',
    '',
    '#include <stdint.h>',
    '',
    '/* VGA 8x8 bitmap font for ASCII 32-126 */',
    '/* Each character: 8 bytes, 1 byte per row, MSB = leftmost pixel */',
    'static const uint8_t font8x8_basic[95][8] = {',
]

for i in range(95):
    ch = i + 32
    if ch in font:
        data = font[ch]
    else:
        data = [0x00] * 8  
    hexvals = ','.join(f'0x{b:02X}' for b in data)
    comment = f" /* {ch} '{chr(ch)}' */" if 32 <= ch <= 126 else f" /* {ch} */"
    lines.append(f'    {{{hexvals}}},{comment}')

lines.append('};')
lines.append('')
lines.append('#endif /* FONT8X8_H */')
lines.append('')

with open('drivers/font8x8.h', 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines))

